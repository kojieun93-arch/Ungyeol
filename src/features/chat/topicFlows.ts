export type FlowOption = {
  value: string;
  label: string; // 버튼
  reply?: string; // 사용자 말풍선 (없으면 label)
  react: string; // 운결의 반응 한마디
};

export type FlowQuestion = { ask: string; options: FlowOption[] };

export type TopicFlow = {
  /** 이 상담의 이름 (진행 표시 · 전환 확인에 사용) */
  name: string;
  greet: string[];
  concern: FlowQuestion;
  /** 고민 답에 따라 다음 질문이 달라짐. null = 후속 질문 없이 바로 기본 정보로 */
  detail: (concern: string) => FlowQuestion | null;
  /** 기본 정보로 넘어가는 한마디 */
  bridge: string;
  /** 상대방 정보: optional(물어보되 쉽게 건너뜀) · encouraged(비교의 핵심이라 먼저 권함) */
  partner?: "optional" | "encouraged";
};

const o = (value: string, label: string, react: string, reply?: string): FlowOption => ({ value, label, react, reply });

